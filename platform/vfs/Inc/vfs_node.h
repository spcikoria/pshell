/**
 * @file    vfs_node.h
 * @brief   Node storage of the virtual file system.
 *
 * The static tree is read-only: its folders and files are const nodes in flash. Any module declares its
 * nodes with the VFS_DIR(), VFS_FILE(), ... macros, the linker collects them into the .vfs_nodes section.
 * A node points to its parent folder, the children of a folder are found by scanning the section, so a
 * module adds files to a folder without touching the module that declared the folder.
 *
 * A file has no content, only handlers: reading or writing it calls them (like sysfs in Linux).
 * A dynamic folder generates its entries with a callback, e.g. /usr/bin lists the shell commands.
 * A mount point hands everything below it to a file system (e.g. FAT on an SD card), see VFS_MountOps_t.
 *
 * @note A node only gets into the image if its object file is linked. Nodes in a static library need
 *       another symbol of the same object file to be referenced, nodes in the application are always linked.
 */
#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/** Longest path, with the terminator */
#define VFS_PATH_MAX (64U)

/** Mode bits, like one octal digit of a Linux mode */
#define VFS_MODE_R (0x4U)
#define VFS_MODE_W (0x2U)
#define VFS_MODE_X (0x1U)

/** Type of a node */
typedef enum
{
    VFS_TYPE_DIR,
    VFS_TYPE_FILE,
    VFS_TYPE_DEVICE,
} VFS_Type_e;

/**
 * @brief  Read handler of a file
 * @note   Runs in the task of the caller, it has to return quickly.
 *         The content is addressed by Offset, returning 0 means the end of the file (otherwise cat never stops).
 * @param[in]  pCtx  Context of the node
 * @param[in]  Offset  Read position, advanced by the returned length
 * @param[out] pBuffer  Buffer of the data
 * @param[in]  Length  Size of the buffer
 * @return Number of bytes read, 0 at the end of the file, or a negative errno value
 */
typedef int32_t (*VFS_ReadHandler_t)(const void *pCtx, uint32_t Offset, void *pBuffer, size_t Length);

/**
 * @brief  Write handler of a file
 * @note   Runs in the task of the caller, it has to return quickly.
 *         One call is one complete value, like in sysfs. The data can end with a line end, as echo adds one.
 * @param[in]  pCtx  Context of the node
 * @param[in]  Offset  Write position, advanced by the returned length
 * @param[in]  pData  Data to write
 * @param[in]  Length  Length of the data
 * @return Number of bytes written, or a negative errno value (e.g. -EINVAL for a value it does not accept)
 */
typedef int32_t (*VFS_WriteHandler_t)(const void *pCtx, uint32_t Offset, const void *pData, size_t Length);

/** Handlers of a file, NULL if the operation is not supported */
typedef struct
{
    VFS_ReadHandler_t Read;
    VFS_WriteHandler_t Write;
} VFS_FileOps_t;

typedef struct VFS_DirOps VFS_DirOps_t;
typedef struct VFS_MountOps VFS_MountOps_t;

/** Description of a node, stored in a static node or generated by a dynamic folder or a file system */
typedef struct
{
    /* Name of the node, without the path, it has to stay valid */
    const char *pName;
    VFS_Type_e Type;
    /* VFS_MODE_x bits */
    uint8_t Mode;
    /* Size in bytes, 0 for a file served by handlers */
    uint32_t Size;
    /* Handlers of a file or a device, NULL for a folder */
    const VFS_FileOps_t *pFileOps;
    /* Entry generator of a dynamic folder, NULL otherwise */
    const VFS_DirOps_t *pDirOps;
    /* File system mounted on the folder, NULL otherwise */
    const VFS_MountOps_t *pMountOps;
    /* Context passed to the handlers */
    const void *pCtx;
} VFS_NodeInfo_t;

/** Entry generator of a dynamic folder */
struct VFS_DirOps
{
    /**
     * @brief  Get an entry of the folder
     * @param[in]  pCtx  Context of the folder
     * @param[in]  Index  Index of the entry, from 0
     * @param[out] pInfo  Description of the entry
     * @return true if the entry exists, false past the last one
     */
    bool (*GetEntry)(const void *pCtx, uint32_t Index, VFS_NodeInfo_t *pInfo);
};

/**
 * Operations of a file system mounted on a folder.
 * The paths are inside the file system, without a leading '/', the root of the file system is never passed.
 * They run in the task of the caller and can block, the file system locks itself.
 * They return 0 or a negative errno value, unless noted.
 */
struct VFS_MountOps
{
    /**
     * @brief  Describe a file or a folder, pName is set by the VFS
     */
    int32_t (*Stat)(const void *pCtx, const char *pPath, VFS_NodeInfo_t *pInfo);

    /**
     * @brief  Open or create a file
     * @param[in]  Flags  O_RDONLY, O_WRONLY or O_RDWR, with O_CREAT, O_EXCL, O_TRUNC, O_APPEND
     * @param[out] ppFile  File object, passed to Close(), Read() and Write()
     */
    int32_t (*Open)(const void *pCtx, const char *pPath, int Flags, void **ppFile);
    int32_t (*Close)(void *pFile);

    /**
     * @return Number of bytes read (0 at the end) or written, or a negative errno value
     */
    int32_t (*Read)(void *pFile, void *pBuffer, size_t Length);
    int32_t (*Write)(void *pFile, const void *pData, size_t Length);

    /**
     * @brief  Open a folder for listing, "" is the root of the file system
     * @param[out] ppDir  Folder object, passed to ReadDir() and CloseDir()
     */
    int32_t (*OpenDir)(const void *pCtx, const char *pPath, void **ppDir);

    /**
     * @brief  Get the next entry, its name stays valid until the next call
     * @return 1 for an entry, 0 at the end, or a negative errno value
     */
    int32_t (*ReadDir)(void *pDir, VFS_NodeInfo_t *pInfo);
    void (*CloseDir)(void *pDir);

    int32_t (*Mkdir)(const void *pCtx, const char *pPath);

    /**
     * @brief  Remove a file or an empty folder, the VFS checks the type before
     */
    int32_t (*Remove)(const void *pCtx, const char *pPath);
};

typedef struct VFS_Node VFS_Node_t;

/** A static node, in the .vfs_nodes section */
struct VFS_Node
{
    /* Parent folder, NULL only for the root */
    const VFS_Node_t *pParent;
    VFS_NodeInfo_t Info;
};

/** A node found by a path, the result of VFS_Lookup(), it must not be copied as pMountPath points into it */
typedef struct
{
    VFS_NodeInfo_t Info;
    /* The static node, NULL for an entry of a dynamic folder or of a mounted file system */
    const VFS_Node_t *pNode;
    /* File system the path is in, NULL outside a mount point */
    const VFS_MountOps_t *pMountOps;
    const void *pMountCtx;
    /* Path inside the file system, "" for the mount point itself, it points into Path */
    const char *pMountPath;
    /* Canonical absolute path */
    char Path[VFS_PATH_MAX];
} VFS_Entry_t;

/** Iterator of a folder, its fields are private */
typedef struct
{
    /* The listed folder */
    VFS_Entry_t Dir;
    /* Next node of the section to check */
    const VFS_Node_t *pNext;
    /* Next entry of the dynamic folder */
    uint32_t DynamicIndex;
    /* Folder object of a mounted file system, NULL otherwise */
    void *pMountDir;
} VFS_Dir_t;

/** The root folder "/" */
extern const VFS_Node_t VFS_RootNode;

/** Handlers of a text file, the context is the null-terminated text */
extern const VFS_FileOps_t VFS_TextOps;

/** Puts a node into the .vfs_nodes section */
#define VFS_NODE_SECTION __attribute__((section(".vfs_nodes"), used, aligned(4)))

/** Declaration of a node, to be used as a parent in another module */
#define VFS_NODE_EXTERN(Symbol) extern const VFS_Node_t Symbol

/** Generic node, use the macros below */
#define VFS_NODE(Symbol, ParentNode, NodeName, NodeType, NodeMode, FileOps, DirOps, MountOps, Context) \
    VFS_NODE_SECTION const VFS_Node_t Symbol = {                                                      \
        .pParent = &(ParentNode),                                                                     \
        .Info = {                                                                                     \
            .pName = (NodeName),                                                                      \
            .Type = (NodeType),                                                                       \
            .Mode = (NodeMode),                                                                       \
            .Size = 0U,                                                                               \
            .pFileOps = (FileOps),                                                                    \
            .pDirOps = (DirOps),                                                                      \
            .pMountOps = (MountOps),                                                                  \
            .pCtx = (Context),                                                                        \
        },                                                                                            \
    }

/** Folder with static children */
#define VFS_DIR(Symbol, ParentNode, NodeName) \
    VFS_NODE(Symbol, ParentNode, NodeName, VFS_TYPE_DIR, VFS_MODE_R | VFS_MODE_X, NULL, NULL, NULL, NULL)

/** Folder with generated entries (it can have static children too, they are listed first) */
#define VFS_DYNAMIC_DIR(Symbol, ParentNode, NodeName, DirOps, Context) \
    VFS_NODE(Symbol, ParentNode, NodeName, VFS_TYPE_DIR, VFS_MODE_R | VFS_MODE_X, NULL, DirOps, NULL, Context)

/** Mount point: the file system serves everything below it, static children of it are hidden */
#define VFS_MOUNT(Symbol, ParentNode, NodeName, MountOps, Context) \
    VFS_NODE(Symbol, ParentNode, NodeName, VFS_TYPE_DIR, VFS_MODE_R | VFS_MODE_W | VFS_MODE_X, NULL, NULL, MountOps, Context)

/** Regular file served by handlers */
#define VFS_FILE(Symbol, ParentNode, NodeName, NodeMode, FileOps, Context) \
    VFS_NODE(Symbol, ParentNode, NodeName, VFS_TYPE_FILE, NodeMode, FileOps, NULL, NULL, Context)

/** Character device served by handlers, shown as 'c' by ls -l */
#define VFS_DEVICE(Symbol, ParentNode, NodeName, NodeMode, FileOps, Context) \
    VFS_NODE(Symbol, ParentNode, NodeName, VFS_TYPE_DEVICE, NodeMode, FileOps, NULL, NULL, Context)

/** Read-only file with a constant text */
#define VFS_TEXT_FILE(Symbol, ParentNode, NodeName, Text) \
    VFS_FILE(Symbol, ParentNode, NodeName, VFS_MODE_R, &VFS_TextOps, Text)

/**
 * @brief  Build a canonical absolute path: no "." and "..", no repeated and no trailing '/'
 * @param[in]  pBase  Canonical absolute path a relative path starts from, NULL for the root
 * @param[in]  pPath  Absolute or relative path
 * @param[out] pOut  Buffer of the result
 * @param[in]  Size  Size of the buffer
 * @return 0, -EINVAL or -ENAMETOOLONG
 */
int32_t VFS_JoinPath(const char *pBase, const char *pPath, char *pOut, size_t Size);

/**
 * @brief  Find the node of a path, a relative path starts from the root
 * @note   Below a mount point the file system is asked. On -ENOENT there pMountOps and pMountPath are still set,
 *         so the missing file or folder can be created.
 * @param[in]  pPath  Path
 * @param[out] pEntry  The node
 * @return 0, -ENOENT, -ENOTDIR, -EINVAL, -ENAMETOOLONG or an error of the file system
 */
int32_t VFS_Lookup(const char *pPath, VFS_Entry_t *pEntry);

/**
 * @brief  Get the description of a node
 * @note   pName is "" for an entry of a mounted file system, the caller has the name in its path
 * @param[in]  pPath  Path
 * @param[out] pInfo  Description of the node
 * @return 0 or a negative errno value, see VFS_Lookup()
 */
int32_t VFS_Stat(const char *pPath, VFS_NodeInfo_t *pInfo);

/**
 * @brief  Start listing a folder, close it with VFS_CloseDir()
 * @param[in]  pPath  Path of the folder
 * @param[out] pDir  Iterator
 * @return 0, -ENOTDIR, an error of VFS_Lookup() or of the file system
 */
int32_t VFS_OpenDir(const char *pPath, VFS_Dir_t *pDir);

/**
 * @brief  Get the next entry of a folder: the static children first, then the generated ones
 * @param[in,out] pDir  Iterator from VFS_OpenDir()
 * @param[out] pInfo  Description of the entry, its name is valid until the next call
 * @return true if an entry was found, false at the end of the folder or on an error
 */
bool VFS_ReadDir(VFS_Dir_t *pDir, VFS_NodeInfo_t *pInfo);

/**
 * @brief  Finish listing a folder, needed after a successful VFS_OpenDir()
 * @param[in,out] pDir  Iterator from VFS_OpenDir()
 */
void VFS_CloseDir(VFS_Dir_t *pDir);

/**
 * @brief  Read handler helper: serve a part of a text, a handler formats its value and calls this
 * @param[in]  pText  Null-terminated text
 * @param[in]  Offset  Read position
 * @param[out] pBuffer  Buffer of the data
 * @param[in]  Length  Size of the buffer
 * @return Number of bytes copied, 0 at the end of the text
 */
int32_t VFS_ReadString(const char *pText, uint32_t Offset, void *pBuffer, size_t Length);
